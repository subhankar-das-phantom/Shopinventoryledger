import PDFDocument from 'pdfkit';
import { ExportDefinition } from './types.js';
import { formatValue } from './helpers.js';
import { Writable } from 'stream';

/**
 * Replace unicode characters that standard PostScript WinAnsi fonts (Helvetica) lack
 * so that PDF exports render cleanly without broken glyphs in any PDF viewer.
 */
const sanitizeForPdfFont = (text: string): string => {
  if (!text) return '';
  return String(text).replace(/₹/g, 'Rs. ');
};

/**
 * Builds an executive-grade PDF document in A4 landscape orientation for wide business ledgers.
 * Returns a Buffer containing the complete PDF data.
 */
export const buildPDF = <T = any>(
  definition: ExportDefinition<T>
): Promise<Buffer> => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: 'A4',
        layout: 'landscape',
        margin: 28,
        bufferPages: true,
        info: {
          Title: definition.title,
          Author: definition.metadata.shopName || 'Shop Inventory Ledger',
          Subject: `${definition.title} Export`,
          Creator: 'Shop Inventory Ledger Accounting Engine'
        }
      });

      const chunks: Buffer[] = [];
      doc.on('data', (chunk: any) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', (err: any) => reject(err));

      renderPdfContent(doc, definition);
    } catch (err) {
      reject(err);
    }
  });
};

/**
 * Streams the executive-grade PDF directly to a Writable stream (e.g. Express Response).
 */
export const streamPDF = <T = any>(
  definition: ExportDefinition<T>,
  stream: Writable
): void => {
  const doc = new PDFDocument({
    size: 'A4',
    layout: 'landscape',
    margin: 28,
    bufferPages: true
  });
  doc.pipe(stream);
  renderPdfContent(doc, definition);
};

function renderPdfContent<T>(doc: any, definition: ExportDefinition<T>): void {
  const pageLeft = doc.page.margins.left;
  const contentWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;

  // Calculate proportional column widths
  let totalWidthWeight = 0;
  definition.columns.forEach((c) => {
    totalWidthWeight += c.width || 15;
  });

  const columns = definition.columns.map((c) => ({
    ...c,
    pdfWidth: ((c.width || 15) / totalWidthWeight) * contentWidth
  }));

  const drawTableHeader = () => {
    const y = doc.y;
    // Dark slate/obsidian header background
    doc.rect(pageLeft, y, contentWidth, 20).fill('#18181b');
    // Electric blue accent border under header
    doc.rect(pageLeft, y + 19, contentWidth, 1).fill('#0284c7');

    doc.font('Helvetica-Bold').fontSize(8).fillColor('#ffffff');
    let x = pageLeft;
    columns.forEach((col) => {
      doc.text(sanitizeForPdfFont(col.header), x + 4, y + 5, {
        width: col.pdfWidth - 8,
        align: col.align || 'left'
      });
      x += col.pdfWidth;
    });
    doc.y = y + 21;
  };

  const drawCell = (
    text: string,
    x: number,
    y: number,
    width: number,
    height: number,
    options: any = {}
  ) => {
    doc.rect(x, y, width, height).stroke('#e2e8f0');
    doc.text(sanitizeForPdfFont(text), x + 4, y + 4.5, {
      width: width - 8,
      height: height - 7,
      ellipsis: true,
      ...options
    });
  };

  const ensureSpace = (neededHeight: number) => {
    if (doc.y + neededHeight <= doc.page.height - doc.page.margins.bottom - 22) {
      return;
    }
    doc.addPage();
    drawTableHeader();
  };

  // Header Banner
  const shopName = definition.metadata.shopName || 'Shop Inventory Ledger';
  doc.font('Helvetica-Bold').fontSize(15).fillColor('#09090b').text(shopName, { align: 'left' });
  doc.moveDown(0.15);

  doc.font('Helvetica-Bold').fontSize(12).fillColor('#27272a').text(definition.title, { align: 'left' });
  doc.moveDown(0.2);

  // Metadata Line
  const metaParts = [
    `Generated: ${formatValue(definition.metadata.generatedAt, 'datetime')}`,
    `Generated By: ${definition.metadata.generatedBy || 'System User'}`
  ];

  if (definition.metadata.filters && Object.keys(definition.metadata.filters).length > 0) {
    const filterText = Object.entries(definition.metadata.filters)
      .map(([k, v]) => `${k}: ${v}`)
      .join(' | ');
    metaParts.push(`Filters: ${filterText}`);
  }

  doc.font('Helvetica').fontSize(7.5).fillColor('#71717a').text(sanitizeForPdfFont(metaParts.join('   •   ')), { align: 'left' });
  doc.moveDown(0.8);

  // Table rendering
  drawTableHeader();

  definition.dataRows.forEach((row, index) => {
    ensureSpace(20);
    const y = doc.y;

    // Alternating zebra striping
    if (index % 2 === 0) {
      doc.rect(pageLeft, y, contentWidth, 20).fill('#f8fafc');
    }

    doc.font('Helvetica').fontSize(7.5).fillColor('#09090b');
    let x = pageLeft;

    columns.forEach((col) => {
      const rawValue = (row as any)[col.key];
      const formatted = col.format ? formatValue(rawValue, col.format) : formatValue(rawValue);
      drawCell(formatted, x, y, col.pdfWidth, 20, { align: col.align || 'left' });
      x += col.pdfWidth;
    });

    doc.y = y + 20;
  });

  // Summary / KPI Box
  if (definition.summary && definition.summary.length > 0) {
    const summaryCardHeight = 22 + definition.summary.length * 15;
    ensureSpace(summaryCardHeight + 20);
    doc.moveDown(0.8);

    const summaryBoxY = doc.y;
    const summaryBoxWidth = Math.min(contentWidth, 400);
    const summaryBoxX = pageLeft + contentWidth - summaryBoxWidth; // align to right side

    // Background & border
    doc.rect(summaryBoxX, summaryBoxY, summaryBoxWidth, summaryCardHeight).fill('#f8fafc');
    doc.rect(summaryBoxX, summaryBoxY, summaryBoxWidth, summaryCardHeight).stroke('#cbd5e1');

    // Header strip
    doc.rect(summaryBoxX, summaryBoxY, summaryBoxWidth, 18).fill('#18181b');
    doc.font('Helvetica-Bold').fontSize(8).fillColor('#ffffff').text(
      'EXECUTIVE SUMMARY & LEDGER TOTALS',
      summaryBoxX + 8,
      summaryBoxY + 5,
      { width: summaryBoxWidth - 16 }
    );

    let currentItemY = summaryBoxY + 23;
    definition.summary.forEach((item) => {
      doc.font('Helvetica').fontSize(7.5).fillColor('#475569').text(
        sanitizeForPdfFont(item.label),
        summaryBoxX + 8,
        currentItemY,
        { width: summaryBoxWidth * 0.58 }
      );

      const formattedVal = item.format ? formatValue(item.value, item.format) : String(item.value);
      doc.font('Helvetica-Bold').fontSize(7.5).fillColor('#0284c7').text(
        sanitizeForPdfFont(formattedVal),
        summaryBoxX + summaryBoxWidth * 0.58,
        currentItemY,
        { width: summaryBoxWidth * 0.38, align: 'right' }
      );

      currentItemY += 15;
    });
  }

  // Running Page Footer
  const pages = doc.bufferedPageRange();
  for (let i = 0; i < pages.count; i++) {
    doc.switchToPage(i);
    const footerY = doc.page.height - doc.page.margins.bottom + 5;
    doc.rect(pageLeft, footerY - 5, contentWidth, 0.5).fill('#e2e8f0');

    doc.font('Helvetica').fontSize(7.5).fillColor('#94a3b8').text(
      `Shop Inventory Ledger  •  Page ${i + 1} of ${pages.count}  •  Strict Immutable Double-Entry Ledger`,
      pageLeft,
      footerY,
      { align: 'center', width: contentWidth }
    );
  }

  doc.end();
}
